/**
 * MORE SETTINGS OF AN ORDERED GRID, for the corpus alone (`Drawn`): the collection draws none of them. A reader
 * that met two settings reads those two; what it must learn is the statement under any wording — other people,
 * other things, other ways to say "at", "before", "just after", "beside" — and only variety teaches that. Every
 * setting numbers its positions from a named end, and "before" is always toward that end.
 *
 * The Russian of a clue keeps the grammar of `Grids.Voice`: `{A}` in the nominative, `{B}` in the genitive (so the
 * words before `{B}` govern the genitive: «после», «впереди», a comparative), both nominative in `near`; a verb in
